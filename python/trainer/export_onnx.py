"""
Export trained GestureNet in two formats:
  1. ONNX model   →  models/gesture_net.onnx
  2. C++ header   →  include/cerebro/model_weights.hpp

The C++ header is a constexpr weight dump that the inference engine links
against at compile time — zero runtime overhead, no ONNX runtime on device.

Usage:
  python -m trainer.export_onnx               # uses models/gesture_net.pt
  python -m trainer.export_onnx --ckpt path/to/gesture_net.pt
"""

import argparse
import os
import sys
from datetime import datetime, timezone

import numpy as np
import torch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from trainer.model import GestureNet

REPO_ROOT  = os.path.join(os.path.dirname(__file__), "..", "..")
MODELS_DIR = os.path.join(REPO_ROOT, "models")
HEADER_OUT = os.path.join(REPO_ROOT, "include", "cerebro", "model_weights.hpp")
ONNX_OUT   = os.path.join(MODELS_DIR, "gesture_net.onnx")


def _fmt_array_1d(name: str, arr: np.ndarray) -> str:
    vals = ", ".join(f"{v:.8f}f" for v in arr.flatten())
    return f"static constexpr float {name}[{arr.size}] = {{{vals}}};\n"


def _fmt_array_2d(name: str, arr: np.ndarray) -> str:
    rows, cols = arr.shape
    lines = []
    for i, row in enumerate(arr):
        row_str = ", ".join(f"{v:.8f}f" for v in row)
        sep = "," if i < rows - 1 else ""
        lines.append(f"    {{{row_str}}}{sep}")
    inner = "\n".join(lines)
    return f"static constexpr float {name}[{rows}][{cols}] = {{\n{inner}\n}};\n"


def generate_header(model: GestureNet, path: str) -> None:
    sd   = model.state_dict()
    w1   = sd["fc1.weight"].cpu().numpy()   # (32, 14)
    b1   = sd["fc1.bias"].cpu().numpy()     # (32,)
    w2   = sd["fc2.weight"].cpu().numpy()   # (16, 32)
    b2   = sd["fc2.bias"].cpu().numpy()     # (16,)
    w3   = sd["fc3.weight"].cpu().numpy()   # (8,  16)
    b3   = sd["fc3.bias"].cpu().numpy()     # (8,)

    ts   = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    lines = [
        "#pragma once\n",
        f"// AUTO-GENERATED by python/trainer/export_onnx.py  ({ts})\n",
        "// DO NOT EDIT MANUALLY — re-run export_onnx.py after training.\n\n",
        "namespace cerebro { namespace weights {\n\n",
        "// Layer 1  [kL1Out=32][kL1In=14]\n",
        _fmt_array_2d("kW1", w1),
        _fmt_array_1d("kB1", b1),
        "\n// Layer 2  [kL2Out=16][kL1Out=32]\n",
        _fmt_array_2d("kW2", w2),
        _fmt_array_1d("kB2", b2),
        "\n// Layer 3  [kL3Out=8][kL2Out=16]\n",
        _fmt_array_2d("kW3", w3),
        _fmt_array_1d("kB3", b3),
        "\n}} // namespace cerebro::weights\n",
    ]

    with open(path, "w") as f:
        f.writelines(lines)
    print(f"C++ header written → {path}")


def export_onnx(model: GestureNet, path: str) -> None:
    model.eval()
    dummy = torch.zeros(1, 14)
    torch.onnx.export(
        model,
        dummy,
        path,
        input_names=["features"],
        output_names=["logits"],
        dynamic_axes={"features": {0: "batch"}, "logits": {0: "batch"}},
        opset_version=17,
    )
    print(f"ONNX model written → {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--ckpt",
        default=os.path.join(MODELS_DIR, "gesture_net.pt"),
        help="Path to PyTorch checkpoint (state_dict)",
    )
    args = parser.parse_args()

    if not os.path.exists(args.ckpt):
        sys.exit(f"Checkpoint not found: {args.ckpt}\nRun: python -m trainer.train first.")

    print(f"Loading checkpoint: {args.ckpt}")
    model = GestureNet()
    model.load_state_dict(torch.load(args.ckpt, weights_only=True))
    model.eval()

    os.makedirs(MODELS_DIR, exist_ok=True)
    generate_header(model, HEADER_OUT)
    export_onnx(model, ONNX_OUT)

    print("\nDone. Rebuild the C++ project to link the updated weights.")


if __name__ == "__main__":
    main()
